def test_dense_embedder_normalization():
    """Verify embedder outputs 128-dimensional normalized float vectors."""
    embedder = LocalDenseEmbedder()
    vec = embedder.embed("simulated fintech banking balance")
    assert len(vec) == 128
    # L2 norm check
    norm = sum(v * v for v in vec)
    assert abs(norm - 1.0) < 1e-4


def test_cosine_similarity_vectors():
    """Verify cosine similarity calculation between identical and orthogonal vectors."""
    vec_a = [1.0, 0.0, 0.0]
    vec_b = [1.0, 0.0, 0.0]
    vec_c = [0.0, 1.0, 0.0]

    assert abs(cosine_similarity_vectors(vec_a, vec_b) - 1.0) < 1e-6
    assert abs(cosine_similarity_vectors(vec_a, vec_c) - 0.0) < 1e-6


def test_persistent_vector_store_persistence():
    """Verify storing and reloading records from disk."""
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp:
        tmp_path = tmp.name

    try:
        store = PersistentVectorStore(persist_path=tmp_path)
        store.add_record(
            chunk_id="chunk_1",
            content="Simulated customer transfer limits are ₹50,000.",
            metadata={"trust_level": "TRUSTED_INTERNAL", "source": "policy.txt"}
        )
        store.save()

        # Reload new store instance from same path
        store2 = PersistentVectorStore(persist_path=tmp_path)
        assert len(store2.records) == 1
        assert "chunk_1" in store2.records
        assert store2.records["chunk_1"]["metadata"]["trust_level"] == "TRUSTED_INTERNAL"
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)


