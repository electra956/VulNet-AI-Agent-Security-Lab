def test_rag_search_with_metadata_contract():
    """Verify search_with_metadata returns the required structured contract."""
    rag = RAGEngine()
    res = rag.search_with_metadata("KYC compliance passport verification")

    assert "query" in res
    assert "retrieved_chunks" in res
    assert "scores" in res
    assert "sources" in res
    assert "trust_levels" in res
    assert "count" in res
    assert len(res["retrieved_chunks"]) == res["count"]
    assert len(res["scores"]) == res["count"]


def test_fintech_policies_knowledge_document_ingested():
    """Verify newly added fintech_policies.txt is indexed and retrieved for approval queries."""
    rag = RAGEngine()
    res = rag.search("dual-control human approval threshold exceeding ₹50,000")
    assert len(res) > 0
    sources = [c["source"] for c in res]
    assert "fintech_policies.txt" in sources
    found = False
    for c in res:
        if c["source"] == "fintech_policies.txt":
            assert "50,000" in c["content"]
            assert c["trust_level"] == "TRUSTED_INTERNAL"
            found = True
            break
    assert found is True
